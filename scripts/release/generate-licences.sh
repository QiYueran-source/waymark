#!/usr/bin/env bash
# Generate THIRD_PARTY_LICENSES.txt with cargo-about.
#
# This is the only place the release licence inventory is produced. The
# packaging script calls it when a maintainer runs a local package, and the CI
# `licences` job calls it once so every archive of one release carries the same
# inventory. If cargo-about is absent the script fails instead of writing a
# placeholder: an inventory that was not generated from Cargo.lock would be a
# false claim about the shipped binaries.
#
# Usage:
#   scripts/release/generate-licences.sh [--out FILE]
#
# cargo-about 0.9 ships its CLI behind the `cli` feature:
#   cargo install --locked --features cli cargo-about

set -euo pipefail
# shellcheck source=lib.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

out="$RELEASE_ROOT/dist/THIRD_PARTY_LICENSES.txt"
while [[ $# -gt 0 ]]; do
    case "$1" in
        --out)
            [[ $# -ge 2 ]] || fail "--out requires a value"
            out="$2"
            shift 2
            ;;
        -h|--help)
            sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        *)
            fail "unknown argument: $1"
            ;;
    esac
done

command -v cargo-about >/dev/null 2>&1 \
    || fail "cargo-about is required to generate the licence inventory. Install it with:
  cargo install --locked --features cli cargo-about"

mkdir -p "$(dirname "$out")"
rm -f "$out"
# --locked keeps the inventory tied to the Cargo.lock the release was cut from;
# the config is a closed accepted-licence list, so an unreviewed licence fails
# this step rather than shipping silently.
cargo-about generate \
    --locked \
    --manifest-path "$WAYMARK_DIR/Cargo.toml" \
    --config "$RELEASE_ROOT/scripts/release/about.toml" \
    --output-file "$out" \
    "$RELEASE_ROOT/scripts/release/about.hbs" \
    || fail "cargo-about could not generate the licence inventory"

[[ -s "$out" ]] || fail "cargo-about wrote an empty licence inventory to $out"
grep -q "generated by cargo-about" "$out" \
    || fail "the licence inventory at $out does not look like a cargo-about document"
printf 'wrote %s (%s lines)\n' "$out" "$(wc -l < "$out" | tr -d ' ')"
